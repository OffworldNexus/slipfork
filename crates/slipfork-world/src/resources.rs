//! Real backing-resource pods (`postgres:18`, `redis:7`, SeaweedFS) and the S3 policy plan.
//!
//! `s3 uploads` stays private: SeaweedFS is configured with a real admin identity, so anonymous
//! requests are rejected (`403`). `s3 assets { cdn static_cdn }` becomes `public-read` by seeding a
//! per-bucket anonymous `Read,List` grant at startup (`s3.anonymous.set`), never by an HTTP shim.

use std::fmt;
use std::path::{Path, PathBuf};

use serde_json::json;

use crate::error::{Error, Result};
use crate::pod::{Bind, BindSource, PodEnv, PodFile, PodSpec};

/// Bucket visibility matching DigitalOcean Spaces.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum S3Policy {
    /// Anonymous `GET` returns `403` (the cloud default).
    Private,
    /// Anonymous `GET` returns `200`; rendered behind `cdn <id>`.
    PublicRead,
}

/// One S3 bucket under a world's `s3` data subvolume.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct S3Bucket {
    name: String,
    policy: S3Policy,
}

impl S3Bucket {
    /// Validates `name` as an S3 bucket name (`3..=63`, lowercase, digits, `.`, `-`).
    pub fn new(name: &str, policy: S3Policy) -> Result<Self> {
        let valid_len = (3..=63).contains(&name.len());
        let valid_chars = name.bytes().all(|byte| {
            byte.is_ascii_lowercase() || byte.is_ascii_digit() || matches!(byte, b'.' | b'-')
        });
        let edges = name
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_alphanumeric())
            && name
                .chars()
                .last()
                .is_some_and(|c| c.is_ascii_alphanumeric());
        if !valid_len || !valid_chars || !edges {
            return Err(Error::InvalidBucket {
                name: name.to_owned(),
            });
        }
        Ok(Self {
            name: name.to_owned(),
            policy,
        })
    }

    /// The validated bucket name.
    #[must_use]
    pub fn name(&self) -> &str {
        &self.name
    }

    /// The bucket visibility.
    #[must_use]
    pub const fn policy(&self) -> S3Policy {
        self.policy
    }
}

/// SeaweedFS admin credentials; `Debug` is fully redacted.
#[derive(Clone, PartialEq, Eq)]
pub struct S3Credentials {
    access_key: String,
    secret_key: String,
}

impl S3Credentials {
    /// Builds the identity written to the tmpfs `s3.json`.
    #[must_use]
    pub fn new(access_key: &str, secret_key: &str) -> Self {
        Self {
            access_key: access_key.to_owned(),
            secret_key: secret_key.to_owned(),
        }
    }
}

impl fmt::Debug for S3Credentials {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("S3Credentials")
            .field("access_key", &"[REDACTED]")
            .field("secret_key", &"[REDACTED]")
            .finish()
    }
}

/// Rendered SeaweedFS bootstrap: `s3.json` identities plus a `weed shell` policy script.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SeaweedfsPlan {
    /// JSON for `-s3.config`, bound read-only from the tmpfs bundle.
    pub s3_config: String,
    /// `weed shell -f` script that creates buckets and grants anonymous reads.
    pub bootstrap: String,
}

impl SeaweedfsPlan {
    /// Renders the static identity file (the single source of truth) and the bucket bootstrap.
    ///
    /// `s3.json` carries the admin identity plus an `anonymous` identity with no credentials whose
    /// actions are scoped to `public-read` buckets only; mixing `s3.configure` with `-s3.config`
    /// is unsupported upstream, so no shell command mutates the policy afterwards.
    pub fn render(credentials: &S3Credentials, buckets: &[S3Bucket]) -> Result<Self> {
        let mut anonymous_actions: Vec<String> = Vec::new();
        let mut bootstrap = String::from(
            "# generated by slipfork-world: static s3.json owns every anonymous grant\n",
        );
        for bucket in buckets {
            bootstrap.push_str(&format!("s3.bucket.create -name {}\n", bucket.name));
            if bucket.policy == S3Policy::PublicRead {
                anonymous_actions.push(format!("Read:{}", bucket.name));
            }
        }
        let config = json!({
            "identities": [
                {
                    "name": "slipfork",
                    "credentials": [{
                        "accessKey": credentials.access_key,
                        "secretKey": credentials.secret_key
                    }],
                    "actions": ["Admin", "Read", "Write", "List", "Tagging"]
                },
                {
                    "name": "anonymous",
                    "actions": anonymous_actions
                }
            ]
        });
        let s3_config = serde_json::to_string_pretty(&config).map_err(|source| Error::Json {
            path: PathBuf::from("-s3.config"),
            source,
        })?;
        Ok(Self {
            s3_config,
            bootstrap,
        })
    }
}

/// A real backing service backed by `worlds/<world>/<data_dir>`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ResourceKind {
    /// `postgres:18` on `:5432`.
    Postgres,
    /// `redis:7` on `:6379`.
    Redis,
    /// SeaweedFS S3 on `:8333` (filer `:8888`, master `:9333`).
    Seaweedfs,
}

impl ResourceKind {
    /// Subvolume name under the world data subvolume.
    #[must_use]
    pub const fn data_dir(self) -> &'static str {
        match self {
            Self::Postgres => "pg",
            Self::Redis => "redis",
            Self::Seaweedfs => "s3",
        }
    }

    /// Loopback port inside the world namespace.
    #[must_use]
    pub const fn port(self) -> u16 {
        match self {
            Self::Postgres => 5432,
            Self::Redis => 6379,
            Self::Seaweedfs => 8333,
        }
    }

    /// Upstream image reference the caller must have pulled.
    #[must_use]
    pub const fn image(self) -> &'static str {
        match self {
            Self::Postgres => "postgres:18",
            Self::Redis => "redis:7",
            // Upstream's real image is `chrislusf/seaweedfs`; there is no `library/seaweedfs`.
            Self::Seaweedfs => "chrislusf/seaweedfs:3.80",
        }
    }
}

/// Facts a pulled image config contributes to a resource pod (env + entrypoint/cmd).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ImageFacts {
    /// Image `config.Env` entries, inherited verbatim.
    pub env: Vec<String>,
    /// Image `config.Entrypoint`.
    pub entrypoint: Vec<String>,
    /// Image `config.Cmd`.
    pub cmd: Vec<String>,
}

/// Builds the resource argv: the image entrypoint/cmd unless the spec overrides it.
fn compose(facts: &ImageFacts, args: &[&str], fallback: &[&str]) -> Vec<String> {
    if facts.entrypoint.is_empty() {
        let chosen = if args.is_empty() { fallback } else { args };
        return chosen.iter().map(|arg| (*arg).to_owned()).collect();
    }
    let mut argv = facts.entrypoint.clone();
    if args.is_empty() {
        argv.extend(facts.cmd.iter().cloned());
        if argv.len() == facts.entrypoint.len() {
            argv.extend(fallback.iter().map(|arg| (*arg).to_owned()));
        }
    } else {
        argv.extend(args.iter().map(|arg| (*arg).to_owned()));
    }
    argv
}

/// `postgres:18` pod: trust auth locally, data on `/var/lib/postgresql/data`.
#[must_use]
pub fn postgres(id: &str, rootfs: &Path, data: &Path, facts: &ImageFacts) -> PodSpec {
    PodSpec {
        id: id.to_owned(),
        rootfs: rootfs.to_path_buf(),
        workdir: "/".to_owned(),
        argv: compose(facts, &[], &["docker-entrypoint.sh", "postgres"]),
        inherited_env: facts.env.clone(),
        env: vec![
            PodEnv::new("PGDATA", "/var/lib/postgresql/data"),
            PodEnv::new("POSTGRES_HOST_AUTH_METHOD", "trust"),
        ],
        binds: vec![Bind {
            source: BindSource::Host(data.to_path_buf()),
            destination: "/var/lib/postgresql/data".to_owned(),
            read_only: false,
        }],
        files: Vec::new(),
    }
}

/// `redis:7` pod: append-only persistence on `/data`, loopback only.
#[must_use]
pub fn redis(id: &str, rootfs: &Path, data: &Path, facts: &ImageFacts) -> PodSpec {
    let flags = [
        "redis-server",
        "--bind",
        "127.0.0.1",
        "--dir",
        "/data",
        "--appendonly",
        "yes",
    ];
    PodSpec {
        id: id.to_owned(),
        rootfs: rootfs.to_path_buf(),
        workdir: "/".to_owned(),
        argv: compose(facts, &flags, &flags),
        inherited_env: facts.env.clone(),
        env: Vec::new(),
        binds: vec![Bind {
            source: BindSource::Host(data.to_path_buf()),
            destination: "/data".to_owned(),
            read_only: false,
        }],
        files: Vec::new(),
    }
}

/// SeaweedFS pod: one `weed server`, then the rendered bucket-policy bootstrap, then `wait`.
#[must_use]
pub fn seaweedfs(
    id: &str,
    rootfs: &Path,
    data: &Path,
    plan: &SeaweedfsPlan,
    facts: &ImageFacts,
) -> PodSpec {
    // The image ships `weed`; `server` runs it in the foreground so signals reach the server.
    // The bootstrap helper (backgrounded) waits for the master and feeds the script on stdin
    // (3.80 has no `weed shell -f`); policy lives in `s3.json`, so no version-dependent verb runs.
    let script = concat!(
        "parent=$$\n",
        "(\n",
        "  tries=0\n",
        "  until printf 's3.bucket.list\\n' | /usr/bin/weed shell -master=127.0.0.1:9333 ",
        ">/dev/null 2>&1; do\n",
        "    tries=$((tries + 1))\n",
        "    if [ \"$tries\" -ge 30 ]; then\n",
        "      echo 'slipfork: seaweedfs master did not answer within 30s; next: read the pod log' >&2\n",
        "      kill -TERM \"$parent\"\n",
        "      exit 1\n",
        "    fi\n",
        "    sleep 1\n",
        "  done\n",
        "  /usr/bin/weed shell -master=127.0.0.1:9333 < /etc/seaweedfs/bootstrap.txt\n",
        ") &\n",
        "exec /usr/bin/weed server -dir=/data -ip=127.0.0.1 -s3 -s3.port=8333 ",
        "-s3.config=/etc/seaweedfs/s3.json -master.port=9333 -volume.port=8080 -filer.port=8888\n"
    );
    PodSpec {
        id: id.to_owned(),
        rootfs: rootfs.to_path_buf(),
        workdir: "/".to_owned(),
        // The image's ENTRYPOINT is `weed`, so the spec must replace it outright: `weed sh -c`
        // would be parsed as a weed subcommand. `/bin/sh -c <script>` runs the bootstrap, which
        // `exec`s `weed server` in the foreground and backgrounds only `weed shell -f`.
        argv: vec!["/bin/sh".to_owned(), "-c".to_owned(), script.to_owned()],
        inherited_env: facts.env.clone(),
        env: Vec::new(),
        binds: vec![
            Bind {
                source: BindSource::Host(data.to_path_buf()),
                destination: "/data".to_owned(),
                read_only: false,
            },
            Bind {
                source: BindSource::Bundle("s3.json".to_owned()),
                destination: "/etc/seaweedfs/s3.json".to_owned(),
                read_only: true,
            },
            Bind {
                source: BindSource::Bundle("bootstrap.txt".to_owned()),
                destination: "/etc/seaweedfs/bootstrap.txt".to_owned(),
                read_only: true,
            },
        ],
        files: vec![
            PodFile {
                name: "s3.json".to_owned(),
                contents: plan.s3_config.clone(),
            },
            PodFile {
                name: "bootstrap.txt".to_owned(),
                contents: plan.bootstrap.clone(),
            },
        ],
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn plan() -> SeaweedfsPlan {
        let buckets = [
            S3Bucket::new("uploads", S3Policy::Private).expect("valid bucket"),
            S3Bucket::new("assets", S3Policy::PublicRead).expect("valid bucket"),
        ];
        SeaweedfsPlan::render(&S3Credentials::new("key", "secret"), &buckets).expect("render")
    }

    #[test]
    fn only_public_read_buckets_receive_an_anonymous_grant() {
        let plan = plan();
        let config: serde_json::Value =
            serde_json::from_str(&plan.s3_config).expect("parse s3.json");
        let identities = config["identities"].as_array().expect("identities");
        assert!(
            identities
                .iter()
                .any(|identity| identity["name"] == "slipfork")
        );
        let anonymous: Vec<&serde_json::Value> = identities
            .iter()
            .filter(|identity| identity["name"] == "anonymous")
            .collect();
        assert_eq!(anonymous.len(), 1, "exactly one anonymous identity");
        assert!(
            anonymous[0].get("credentials").is_none(),
            "the anonymous identity must carry no credentials"
        );
        assert_eq!(
            anonymous[0]["actions"]
                .as_array()
                .expect("anonymous actions")
                .iter()
                .filter_map(|action| action.as_str())
                .collect::<Vec<_>>(),
            ["Read:assets"],
            "anonymous access is scoped to the public bucket only"
        );
        assert!(!plan.s3_config.contains("Read:uploads"));
        assert!(!plan.bootstrap.contains("s3.anonymous"));
        assert!(!plan.bootstrap.contains("s3.configure"));
        assert!(plan.bootstrap.contains("s3.bucket.create -name uploads"));
        assert!(plan.bootstrap.contains("s3.bucket.create -name assets"));
        assert!(plan.s3_config.contains("\"Admin\""));
    }

    #[test]
    fn credentials_are_redacted_and_bucket_names_are_validated() {
        let credentials = S3Credentials::new("AKIA", "topsecret");
        let debug = format!("{credentials:?}");
        assert!(!debug.contains("AKIA"));
        assert!(!debug.contains("topsecret"));
        for bad in ["", "ab", "UPPER", "-lead", "trail-", "with space"] {
            assert!(
                S3Bucket::new(bad, S3Policy::Private).is_err(),
                "`{bad}` must not be a bucket"
            );
        }
        assert!(S3Bucket::new("static-cdn.assets", S3Policy::PublicRead).is_ok());
    }

    #[test]
    fn resource_pods_mount_their_data_subvolume_and_bundle_config() {
        let rootfs = Path::new("/images/pg");
        let data = Path::new("/store/worlds/demo/pg");
        let facts = ImageFacts {
            env: vec![
                "PATH=/usr/local/bin:/usr/bin".to_owned(),
                "PG_MAJOR=18".to_owned(),
            ],
            entrypoint: vec!["docker-entrypoint.sh".to_owned()],
            cmd: vec!["postgres".to_owned()],
        };
        let spec = postgres("pg", rootfs, data, &facts);
        assert_eq!(spec.argv, ["docker-entrypoint.sh", "postgres"]);
        assert_eq!(spec.inherited_env, facts.env);
        assert_eq!(spec.binds[0].destination, "/var/lib/postgresql/data");
        assert_eq!(spec.binds[0].source, BindSource::Host(data.to_path_buf()));
        assert!(spec.validate().is_ok());

        let redis_spec = redis("cache", rootfs, data, &facts);
        assert_eq!(
            redis_spec.argv,
            [
                "docker-entrypoint.sh",
                "redis-server",
                "--bind",
                "127.0.0.1",
                "--dir",
                "/data",
                "--appendonly",
                "yes"
            ]
        );
        assert!(redis_spec.argv.iter().any(|arg| arg == "127.0.0.1"));
        assert!(redis_spec.validate().is_ok());

        let plan = plan();
        let s3 = seaweedfs(
            "uploads",
            Path::new("/images/s3"),
            Path::new("/store/worlds/demo/s3"),
            &plan,
            &facts,
        );
        assert_eq!(s3.inherited_env, facts.env);
        assert_eq!(s3.argv[..2], ["/bin/sh", "-c"]);
        let script = &s3.argv[2];
        assert!(
            script.contains("exec /usr/bin/weed server"),
            "the server must own the foreground process: {script}"
        );
        assert!(
            script.contains("< /etc/seaweedfs/bootstrap.txt"),
            "the bootstrap script must be fed on stdin: {script}"
        );
        assert!(
            script.contains("until printf 's3.bucket.list"),
            "readiness must be retried before the bootstrap: {script}"
        );
        assert!(
            !script.contains("s3.anonymous"),
            "no version-dependent policy verb may remain: {script}"
        );
        assert!(
            !script.contains(" -f "),
            "weed shell 3.80 has no `-f` flag: {script}"
        );
        assert!(
            s3.files.iter().any(|file| file.name == "bootstrap.txt"),
            "the bootstrap must ride the tmpfs bundle"
        );
        assert_eq!(s3.files.len(), 2);
        assert!(s3.validate().is_ok());
        assert_eq!(
            ResourceKind::Seaweedfs.image(),
            "chrislusf/seaweedfs:3.80",
            "there is no `library/seaweedfs` on Hub"
        );
        let argv = s3.argv.join(" ");
        assert!(
            argv.contains("exec /usr/bin/weed server -dir=/data -ip=127.0.0.1 -s3"),
            "{argv}"
        );
        assert!(
            !argv.contains("wait "),
            "weed server must stay in the foreground"
        );
    }
}
