"""Tests for tools/check_zed_extension.py against real on-disk extension trees."""

from __future__ import annotations

import importlib.util
import shutil
import sys
from pathlib import Path

import pytest

MODULE_PATH = Path(__file__).resolve().parents[1] / "check_zed_extension.py"
SPEC = importlib.util.spec_from_file_location("check_zed_extension", MODULE_PATH)
assert SPEC is not None and SPEC.loader is not None
checker = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = checker
SPEC.loader.exec_module(checker)

EXTENSION_TOML = """\
id = "forkfile"
name = "Forkfile"
schema_version = 1

[grammars.forkfile]
path = "../tree-sitter-forkfile"
rev = "0123456789abcdef0123456789abcdef01234567"

[language_servers.slipfork-lsp]
name = "Slipfork LSP"
languages = ["Forkfile"]

[language_servers.slipfork-lsp.language_ids]
Forkfile = "forkfile"
"""

CARGO_TOML = """\
[package]
name = "forkfile"
version = "0.1.0"

[lib]
crate-type = ["cdylib"]

[dependencies]
zed_extension_api = "0.7.0"

[workspace]
"""

LIB_RS = """\
use zed_extension_api as zed;

fn command(worktree: &zed::Worktree) -> zed::Result<zed::Command> {
    let command = worktree.which("slipfork").unwrap();
    Ok(zed::Command { command, args: vec!["lsp".to_string()], env: Vec::new() })
}
"""

CONFIG_TOML = """\
name = "Forkfile"
grammar = "forkfile"
path_suffixes = ["Forkfile", "forkfile"]
line_comments = ["# "]
"""

HIGHLIGHTS = """\
(comment) @comment
(string) @string
(service_statement name: (identifier) @type)
"""

CORPUS = """\
==================
Project
==================

project demo

---

(source_file
  (project_statement
    name: (identifier)))
"""


def build_repo(root: Path) -> Path:
    grammar = root / "editors" / "tree-sitter-forkfile"
    (grammar / "src").mkdir(parents=True)
    (grammar / "queries").mkdir()
    (grammar / "test" / "corpus").mkdir(parents=True)
    (grammar / "grammar.js").write_text(
        "module.exports = grammar({ name: 'forkfile' });\n"
    )
    (grammar / "src" / "parser.c").write_text(
        "// generated by tree-sitter\nconst TSLanguage *tree_sitter_forkfile(void);\n"
    )
    (grammar / "src" / "grammar.json").write_text(
        '{"name": "forkfile", "rules": {"source_file": {"type": "SYMBOL"}}}\n'
    )
    (grammar / "src" / "node-types.json").write_text(
        '[{"type": "source_file", "named": true}]\n'
    )
    (grammar / "queries" / "highlights.scm").write_text(HIGHLIGHTS)
    (grammar / "test" / "corpus" / "statements.txt").write_text(CORPUS)

    extension = root / "editors" / "zed"
    language = extension / "languages" / "forkfile"
    language.mkdir(parents=True)
    (extension / "src").mkdir()
    (extension / "extension.toml").write_text(EXTENSION_TOML)
    (extension / "Cargo.toml").write_text(CARGO_TOML)
    (extension / "src" / "lib.rs").write_text(LIB_RS)
    (language / "config.toml").write_text(CONFIG_TOML)
    (language / "highlights.scm").write_text(HIGHLIGHTS)
    (language / "brackets.scm").write_text('("{" @open "}" @close)\n')

    cli = root / "crates" / "slipfork" / "src" / "cli"
    cli.mkdir(parents=True)
    (cli / "commands.rs").write_text("pub enum Commands {\n    Lsp,\n}\n")
    return root


def run(root: Path, capsys: pytest.CaptureFixture[str]) -> tuple[int, str, str]:
    code = checker.main([str(root)])
    captured = capsys.readouterr()
    return code, captured.out, captured.err


def test_committed_extension_passes(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = build_repo(tmp_path)
    code, out, err = run(root, capsys)
    assert code == checker.EXIT_OK, err
    assert "✓" in out
    assert err == ""


def test_missing_parser_c_fails(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = build_repo(tmp_path)
